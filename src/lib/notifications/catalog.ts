/**
 * What a notification IS, in one place.
 *
 * The old system spread this over three files that disagreed with each other:
 * a link map in target.ts, an icon switch in NotificationBell.tsx, and a
 * separate SMS list in sms-kinds.ts. Adding an event meant editing three
 * places and forgetting one — which is how `listing_published` ended up
 * pointing at "/sell", a route that now redirects to the BLANK publish form.
 * A seller told "your annonce is online" was taken to an empty form.
 *
 * The audit that produced this file, against the live database:
 *
 *   • 1 372 notifications, 1 355 unread. 1 240 of them are two machine kinds
 *     (auction_ended_unsold, auction_live_seller) generated by the relisting
 *     loop, about auctions that no longer exist.
 *   • Every kind with any volume is auction-era. Not one listing_* row has
 *     ever been written.
 *   • The single event this product is built around — a buyer revealing a
 *     seller's phone number — notifies nobody at all.
 *   • Dead destinations: /kyc/status (feature deleted), /admin/kyc-queue,
 *     /account/inspections, /sell#payouts, and every /auctions/<id> link now
 *     that the auctions are gone.
 *
 * So: one catalogue. Each kind declares who it is for, how it looks, where it
 * goes (from its own payload), and whether it is worth an SMS. Anything not
 * listed here is legacy — it still renders, quietly, and links home.
 */

export type NotificationAudience = "seller" | "buyer" | "admin";
export type NotificationTone = "good" | "bad" | "warn" | "info";

export type NotificationPayload = {
  listing_id?: string;
  listing_title?: string;
  payment_id?: string;
  [key: string]: unknown;
};

export type NotificationKindDef = {
  /** Icon name, resolved to a lucide component by the renderer. */
  icon:
    | "phone"
    | "check"
    | "x"
    | "clock"
    | "receipt"
    | "megaphone"
    | "sparkles"
    | "wrench"
    | "bell";
  tone: NotificationTone;
  audience: NotificationAudience;
  /** Short label above the title in the list. */
  label: string;
  /**
   * Where tapping it should land. Takes the row's payload and its stored
   * `link` column: enqueue_notification has no payload parameter, so most rows
   * carry their entity in the link and nothing else.
   */
  href: (p: NotificationPayload, link?: string | null) => string;
  /**
   * Worth interrupting someone's day by SMS. Deliberately short: an SMS costs
   * money and attention, so it is reserved for things that are time-bound or
   * that make the seller money.
   */
  sms?: boolean;
};

const LISTING_LINK = /^\/annonces\/[0-9a-fA-F-]{36}$/;

const listingHref = (p: NotificationPayload, link?: string | null) =>
  p.listing_id
    ? `/annonces/${p.listing_id}`
    : link && LISTING_LINK.test(link)
      ? link
      : "/account/listings";


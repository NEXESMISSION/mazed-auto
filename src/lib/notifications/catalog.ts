/** Everything the renderer needs, including for a kind we no longer send. */
export function describeKind(kind: string): NotificationKindDef {
  return (
    NOTIFICATION_KINDS[kind] ?? {
      icon: "bell",
      tone: "info",
      audience: "buyer",
      label: "Notification",
      // A legacy row (an auction that no longer exists, a KYC page that was
      // deleted) must never strand the user on a 404: home, not its old link.
      href: () => "/",
    }
  );
}

/** The destination for a row, ignoring any stale `link` column it carries. */
export function notificationHref(
  kind: string,
  payload: NotificationPayload | null | undefined,
  storedLink?: string | null,
): string {
  const known = NOTIFICATION_KINDS[kind];
  if (known) return known.href(payload ?? {}, storedLink);
  // Unknown kind: trust the stored link only if it points somewhere that still
  // exists. /auctions, /kyc, /sell and /properties were all removed or
  // repurposed by the v3 pivot.
  if (storedLink && !/^\/(auctions|kyc|properties|sell|inspector)/.test(storedLink)) {
    return storedLink;
  }
  return "/";
}

/** Kinds that justify an SMS. */
export const SMS_KINDS: string[] = Object.entries(NOTIFICATION_KINDS)
  .filter(([, def]) => def.sms)
  .map(([kind]) => kind);

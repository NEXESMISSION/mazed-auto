import * as React from "react";
import { cn } from "@/lib/utils";

export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverable?: boolean }
>(({ className, hoverable, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-[var(--radius-md)] bg-[var(--surface)] border border-[var(--border)] overflow-hidden",
      hoverable &&
        "transition-all hover:border-[var(--gold)] hover:shadow-[var(--shadow-md)] cursor-pointer",
      className,
    )}
    {...props}
  />
));
Card.displayName = "Card";

